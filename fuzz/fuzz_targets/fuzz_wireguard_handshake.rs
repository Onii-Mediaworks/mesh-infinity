// fuzz_targets/fuzz_wireguard_handshake.rs — link handshake parsers (§5.1, §5.2)
//
// # What this target tests
//
// Every direct link starts with the Noise_IK-shaped handshake in
// `backend/transport/wireguard.rs`.  Its two messages, and the two trusted-
// tunnel PSK agreement messages plus the signed tunnel-key binding in
// `backend/transport/tunnel_keys.rs`, arrive from peers that may be hostile.
// Each parser must be total over arbitrary bytes, and the responder must
// reject anything that is not a key-confirmed Init from the expected peer
// *before* touching session state.
//
// # Attack surface
//
// Inputs may be random bytes, truncated or padded messages, a foreign suite
// id or protocol version in the header (fixed-suite rule, §5.1), a valid
// header with garbage fields, a genuine Init with a flipped byte, or a
// replayed Init.  All must come back as `Err`, never a panic, and only the
// genuine Init from the fixed corpus keys may produce a session.
//
// # Harness layout
//
// The input is fed, independently, to:
//   1. `HandshakeInit::from_bytes` → `respond_to_handshake` with fixed
//      responder keys and `TunnelPsk::None` (the no-PSK baseline);
//   2. `HandshakeResponse::from_bytes` → `PendingInitiatorHandshake::complete`
//      against a fixed, deterministic pending handshake;
//   3. `PskInit::from_bytes`, `PskResponse::from_bytes` and
//      `TunnelKeyBinding::from_bytes` (+ `verify_for`).
//
// # Corpus
//
// `fuzz/corpus/fuzz_wireguard_handshake/` holds one valid Init generated
// from the fixed keys below (regenerated by
// `wireguard::tests::test_print_corpus_valid_init`) and malformed variants.

#![no_main]

use libfuzzer_sys::fuzz_target;

use mesh_infinity::identity::peer_id::PeerId;
use mesh_infinity::transport::tunnel_keys::{PskInit, PskResponse, TunnelKeyBinding};
use mesh_infinity::transport::wireguard::{
    respond_to_handshake, HandshakeInit, HandshakeResponse, PendingInitiatorHandshake, TunnelPsk,
};

/// Fixed keys shared with the corpus and the in-tree replay test.
const INIT_STATIC: [u8; 32] = [0xAA; 32];
const RESP_STATIC: [u8; 32] = [0xBB; 32];
const EPHEMERAL: [u8; 32] = [0xCC; 32];
const TIMESTAMP: u64 = 1_700_000_000;

fuzz_target!(|data: &[u8]| {
    let init_secret = x25519_dalek::StaticSecret::from(INIT_STATIC);
    let init_pub = x25519_dalek::PublicKey::from(&init_secret);
    let resp_secret = x25519_dalek::StaticSecret::from(RESP_STATIC);
    let resp_pub = x25519_dalek::PublicKey::from(&resp_secret);
    let initiator_id = PeerId([0x11; 32]);
    let responder_id = PeerId([0x22; 32]);

    // 1. Responder side: parse, then respond with a recorded last timestamp
    //    so a replayed corpus Init exercises the replay branch too.
    if let Ok(init) = HandshakeInit::from_bytes(data) {
        for last in [None, Some(TIMESTAMP)] {
            let _ = respond_to_handshake(
                &init,
                &resp_secret,
                &init_pub,
                &TunnelPsk::None,
                responder_id,
                initiator_id,
                last,
            );
        }
    }

    // 2. Initiator side: a deterministic pending handshake must reject every
    //    response the fuzzer can produce (it cannot know resp_secret).
    if let Ok(response) = HandshakeResponse::from_bytes(data) {
        if let Ok((pending, _)) = PendingInitiatorHandshake::new_with_ephemeral(
            x25519_dalek::StaticSecret::from(INIT_STATIC),
            resp_pub,
            TunnelPsk::None,
            TIMESTAMP,
            EPHEMERAL,
        ) {
            let _ = pending.complete(&response, initiator_id, responder_id);
        }
    }

    // 3. PSK agreement and binding parsers: structure only, plus the binding
    //    signature/KEM-key gate against a fixed identity key.
    let _ = PskInit::from_bytes(data);
    let _ = PskResponse::from_bytes(data);
    if let Ok(binding) = TunnelKeyBinding::from_bytes(data) {
        let _ = binding.verify_for(&[0x77; 32]);
    }
});
